package com.squareup.wire.internal

import com.squareup.wire.KotlinConstructorBuilder
import com.squareup.wire.Message
import com.squareup.wire.OneOf
import com.squareup.wire.ProtoAdapter
import com.squareup.wire.WireBoxedOneof
import com.squareup.wire.WireField
import java.lang.reflect.Field

internal class OneOfBinding<M : Message<M, B>, B : Message.Builder<M, B>> internal constructor(
  private val messageField: Field,
  builderType: Class<B>,
  private val key: OneOf.Key<*>,
  override val writeIdentityValues: Boolean,
) : FieldOrOneOfBinding<M, B>() {
  init {
    messageField.isAccessible = true
  }

  // When there is no explicit Builder (`javaInterop = false`), KotlinConstructorBuilder is used.
  // It has no message-specific fields, so it keeps the value of the oneof in a side map.
  private val isKotlinConstructorBuilder: Boolean =
    builderType == KotlinConstructorBuilder::class.java

  private val builderField: Field? = if (isKotlinConstructorBuilder) {
    // Code generated by an older Wire has no annotation that tells KotlinConstructorBuilder where
    // the oneof goes among the constructor parameters. Fail now instead of when decoding.
    check(messageField.isAnnotationPresent(WireBoxedOneof::class.java)) {
      "${messageField.declaringClass.name}.${messageField.name} is a boxed oneof without " +
        "@WireBoxedOneof, so Wire cannot build it reflectively without a Builder class. " +
        "Regenerate this code with a newer version of Wire."
    }
    null
  } else {
    builderType.getDeclaredField(messageField.name).also { it.isAccessible = true }
  }

  override val tag: Int
    get() = key.tag

  override val label: WireField.Label
    get() = WireField.Label.OPTIONAL

  override val redacted: Boolean
    get() = key.redacted

  override val wireFieldJsonName: String
    get() = key.jsonName

  override val name: String
    get() = key.declaredName

  override val declaredName: String
    get() = key.declaredName

  override val isMap: Boolean
    get() = false

  override val isMessage: Boolean
    get() = Message::class.java.isAssignableFrom(singleAdapter.type?.javaObjectType)

  override val keyAdapter
    get() = error("not a map")

  @Suppress("UNCHECKED_CAST")
  override val singleAdapter
    get() = key.adapter as ProtoAdapter<Any>

  override fun value(builder: B, value: Any?) {
    set(builder, value)
  }

  override fun set(builder: B, value: Any?) {
    @Suppress("UNCHECKED_CAST")
    val oneOf = if (value != null) OneOf(key as OneOf.Key<Any>, value) else null
    setOneOf(builder, oneOf)
  }

  override fun setFromJson(builder: B, value: Any?) {
    // Binary decoding keeps the last member of a oneof. JSON decoding rejects two members.
    if (value != null) {
      val existing = getOneOf(builder)
      if (existing != null && existing.key != key) {
        throw duplicateOneOfMember(messageField.name, existing.key.declaredName, name)
      }
    }
    set(builder, value)
  }

  override fun get(message: M): Any? {
    val oneOfOrNull = messageField.get(message) as OneOf<*, *>?
    return oneOfOrNull?.getOrNull(key)
  }

  override fun getFromBuilder(builder: B): Any? = getOneOf(builder)?.getOrNull(key)

  private fun getOneOf(builder: B): OneOf<*, *>? = if (isKotlinConstructorBuilder) {
    @Suppress("UNCHECKED_CAST")
    (builder as KotlinConstructorBuilder<M, B>).getOneOf(messageField.name) as OneOf<*, *>?
  } else {
    builderField!!.get(builder) as OneOf<*, *>?
  }

  private fun setOneOf(builder: B, oneOf: OneOf<*, *>?) {
    if (isKotlinConstructorBuilder) {
      @Suppress("UNCHECKED_CAST")
      (builder as KotlinConstructorBuilder<M, B>).setOneOf(messageField.name, oneOf)
    } else {
      builderField!!.set(builder, oneOf)
    }
  }
}

/**
 * Returns the exception that JSON decoding throws when the input sets two members of the oneof
 * named [oneOfName]. This follows the message of generated code for flat oneofs.
 */
internal fun duplicateOneOfMember(
  oneOfName: String,
  firstMember: String,
  secondMember: String,
): IllegalArgumentException = IllegalArgumentException(
  "At most one of $firstMember, $secondMember may be non-null in oneof $oneOfName",
)
