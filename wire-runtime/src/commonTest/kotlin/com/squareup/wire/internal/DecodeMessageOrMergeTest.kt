package com.squareup.wire.internal

import assertk.assertFailure
import assertk.assertThat
import assertk.assertions.hasMessage
import assertk.assertions.isEqualTo
import assertk.assertions.isInstanceOf
import com.squareup.wire.FieldEncoding
import com.squareup.wire.ProtoAdapter
import com.squareup.wire.ProtoReader
import com.squareup.wire.ProtoReader32
import com.squareup.wire.ProtoWriter
import com.squareup.wire.Syntax.PROTO_3
import com.squareup.wire.forEachTag
import kotlin.test.Test
import okio.Buffer
import okio.ByteString
import okio.IOException

class DecodeMessageOrMergeTest {
  /**
   * Mirrors code generated by Wire for `message Node { Node child = 1; repeated int32 values = 2; }`.
   * When [readsProtoReader32] is false it only decodes [ProtoReader], like code generated before
   * [ProtoReader32] existed, so a [ProtoReader32] is adapted to a [ProtoReader].
   * When [defersMerges] is true it keeps later occurrences and merges them once after the last tag,
   * like current generated code.
   */
  private class Node(val child: Node?, val values: List<Int>) {
    override fun toString(): String = "Node(child=$child, values=$values)"
  }

  private class NodeAdapter(
    private val readsProtoReader32: Boolean,
    val defersMerges: Boolean = false,
  ) : ProtoAdapter<Node>(
    FieldEncoding.LENGTH_DELIMITED,
    Node::class,
    "type.googleapis.com/Node",
    PROTO_3,
    null,
  ) {
    override fun redact(value: Node) = value

    override fun encodedSize(value: Node): Int {
      var size = encodedSizeWithTag(1, value.child)
      for (v in value.values) size += INT32.encodedSizeWithTag(2, v)
      return size
    }

    override fun encode(writer: ProtoWriter, value: Node) {
      encodeWithTag(writer, 1, value.child)
      for (v in value.values) INT32.encodeWithTag(writer, 2, v)
    }

    override fun decode(reader: ProtoReader): Node {
      var child: Node? = null
      var merges: MessageMerges? = null
      val values = mutableListOf<Int>()
      reader.forEachTag { tag ->
        when (tag) {
          1 -> when {
            !defersMerges -> child = decodeMessageOrMerge(this, reader, child)
            child == null -> child = decode(reader)
            else -> merges = addMerge(merges, reader, 1)
          }
          2 -> values += INT32.decode(reader)
          else -> reader.readUnknownField(tag)
        }
      }
      if (merges != null) child = finishMerge(merges, 1, this, child)
      return Node(child, values)
    }

    override fun decode(reader: ProtoReader32): Node {
      if (!readsProtoReader32) return super.decode(reader)
      var child: Node? = null
      var merges: MessageMerges? = null
      val values = mutableListOf<Int>()
      reader.forEachTag { tag ->
        when (tag) {
          1 -> when {
            !defersMerges -> child = decodeMessageOrMerge(this, reader, child)
            child == null -> child = decode(reader)
            else -> merges = addMerge(merges, reader, 1)
          }
          2 -> values += INT32.decode(reader)
          else -> reader.readUnknownField(tag)
        }
      }
      if (merges != null) child = finishMerge(merges, 1, this, child)
      return Node(child, values)
    }
  }

  private val adapters = listOf(
    NodeAdapter(readsProtoReader32 = true),
    NodeAdapter(readsProtoReader32 = false),
    NodeAdapter(readsProtoReader32 = true, defersMerges = true),
    NodeAdapter(readsProtoReader32 = false, defersMerges = true),
  )

  private operator fun ByteString.plus(other: ByteString): ByteString = Buffer().write(this).write(other).readByteString()

  private fun lengthDelimited(tag: Int, value: ByteString): ByteString {
    val buffer = Buffer()
    ProtoAdapter.BYTES.encodeWithTag(ProtoWriter(buffer), tag, value)
    return buffer.readByteString()
  }

  private fun int32(tag: Int, value: Int): ByteString {
    val buffer = Buffer()
    ProtoAdapter.INT32.encodeWithTag(ProtoWriter(buffer), tag, value)
    return buffer.readByteString()
  }

  /** Each level is an empty child followed by a child that holds the next level. */
  private fun nestedMerges(levels: Int): ByteString {
    var current = ByteString.EMPTY
    repeat(levels) {
      current = lengthDelimited(1, ByteString.EMPTY) + lengthDelimited(1, current)
    }
    return current
  }

  private fun decodeAll(adapter: ProtoAdapter<Node>, bytes: ByteString, block: (Node) -> Unit) {
    block(adapter.decode(bytes.toByteArray()))
    block(adapter.decode(Buffer().write(bytes)))
  }

  @Test fun twoOccurrencesAreMerged() {
    val first = int32(2, 1) + lengthDelimited(1, int32(2, 10))
    val second = int32(2, 2) + lengthDelimited(1, int32(2, 20))
    val bytes = lengthDelimited(1, first) + lengthDelimited(1, second)
    for (adapter in adapters) {
      decodeAll(adapter, bytes) { node ->
        assertThat(node.toString()).isEqualTo(
          "Node(child=Node(child=Node(child=null, values=[10, 20]), values=[1, 2]), values=[])",
        )
      }
    }
  }

  @Test fun someHundredsOfOccurrencesAreMerged() {
    val buffer = Buffer()
    repeat(400) { occurrence ->
      val node = Buffer()
      repeat(20) { node.write(int32(2, occurrence)) }
      buffer.write(lengthDelimited(1, node.readByteString()))
    }
    val bytes = buffer.readByteString()
    for (adapter in adapters) {
      decodeAll(adapter, bytes) { node ->
        assertThat(node.child!!.values.size).isEqualTo(8_000)
      }
    }
  }

  @Test fun mergedMessagesShareTheRecursionLimit() {
    for (adapter in adapters) {
      for (levels in listOf(150, 5_000)) {
        val bytes = nestedMerges(levels)
        assertFailure { adapter.decode(bytes.toByteArray()) }
          .isInstanceOf<IOException>().hasMessage("Wire recursion limit exceeded")
        assertFailure { adapter.decode(Buffer().write(bytes)) }
          .isInstanceOf<IOException>().hasMessage("Wire recursion limit exceeded")
      }
    }
  }

  @Test fun mergedMessagesWithinTheRecursionLimitAreDecoded() {
    val bytes = nestedMerges(50)
    for (adapter in adapters) {
      decodeAll(adapter, bytes) { node ->
        var depth = 0
        var current: Node? = node
        while (current != null) {
          depth++
          current = current.child
        }
        assertThat(depth).isEqualTo(51)
      }
    }
  }

  @Test fun mergedMessagesShareACustomRecursionLimit() {
    val bytes = nestedMerges(20)
    for (adapter in adapters) {
      assertFailure { adapter.decode(ProtoReader32(bytes, recursionLimit = 10)) }
        .isInstanceOf<IOException>().hasMessage("Wire recursion limit exceeded")
      assertFailure { adapter.decode(ProtoReader(Buffer().write(bytes), 10)) }
        .isInstanceOf<IOException>().hasMessage("Wire recursion limit exceeded")
      adapter.decode(ProtoReader32(bytes, recursionLimit = 30))
      adapter.decode(ProtoReader(Buffer().write(bytes), 30))
    }
  }

  @Test fun manyOccurrencesOfOneFieldAreRejected() {
    val bytes = manyOccurrences(40_000)
    for (adapter in adapters.filter { !it.defersMerges }) {
      assertFailure { adapter.decode(bytes.toByteArray()) }.isInstanceOf<ProtocolException>()
      assertFailure { adapter.decode(Buffer().write(bytes)) }.isInstanceOf<ProtocolException>()
    }
  }

  @Test fun manyOccurrencesOfOneFieldAreMergedOnce() {
    val bytes = manyOccurrences(200_000)
    for (adapter in adapters.filter { it.defersMerges }) {
      decodeAll(adapter, bytes) { node ->
        assertThat(node.child!!.values.size).isEqualTo(400_000)
      }
    }
  }

  private fun manyOccurrences(count: Int): ByteString {
    val buffer = Buffer()
    val occurrence = lengthDelimited(1, int32(2, 1) + int32(2, 1))
    repeat(count) { buffer.write(occurrence) }
    return buffer.readByteString()
  }
}
