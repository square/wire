import okio.ByteString

private class ChoiceKey<T>(tag: Int, adapter: ProtoAdapter<T>) : OneOf.Key<T>(tag, adapter, "key$tag")

private val NODE = ChoiceKey(1, NodeAdapter(readsProtoReader32 = true))
private val TEXT = ChoiceKey(2, ProtoAdapter.STRING)
private val VALUE = ChoiceKey(3, ProtoAdapter.STRUCT_VALUE)
private val WRAPPED = ChoiceKey(4, ProtoAdapter.STRING_VALUE)
private val KEYS = listOf(NODE, TEXT, VALUE, WRAPPED)

private enum class Mode { DEFER, MERGE }

/** Mirrors code generated by Wire for a message with one boxed oneof, decoded the way [mode] says. */
private class Holder(val choice: OneOf<ChoiceKey<*>, *>?) {
  override fun toString(): String = "Holder(choice=$choice)"
}

private class HolderAdapter(private val mode: Mode) :
  ProtoAdapter<Holder>(
    FieldEncoding.LENGTH_DELIMITED,
    Holder::class,
    "type.googleapis.com/Holder",
    PROTO_3,
    null,
  ) {
  override fun redact(value: Holder) = value

  override fun encodedSize(value: Holder): Int = value.choice?.encodedSizeWithTag() ?: 0

  override fun encode(writer: ProtoWriter, value: Holder) {
    value.choice?.encodeWithTag(writer)
  }

  override fun decode(reader: ProtoReader): Holder {
    var choice: OneOf<ChoiceKey<*>, *>? = null
    reader.forEachTag { tag ->
      for (key in KEYS) {
        if (tag == key.tag) {
          choice = when (mode) {
            Mode.DEFER -> decodeOneOfOrDefer(key, reader, choice)
            Mode.MERGE -> decodeOneOfOrMerge(key, reader, choice)
          }
          return@forEachTag key
        }
      }
      reader.readUnknownField(tag)
    }
    if (mode == Mode.DEFER && hasMerges(reader)) {
      choice = finishOneOfMerge(reader, choice)
      endMerges(reader)
    }
    return Holder(choice)
  }

  override fun decode(reader: ProtoReader32): Holder {
    var choice: OneOf<ChoiceKey<*>, *>? = null
    reader.forEachTag { tag ->
      for (key in KEYS) {
        if (tag == key.tag) {
          choice = when (mode) {
            Mode.DEFER -> decodeOneOfOrDefer(key, reader, choice)
            Mode.MERGE -> decodeOneOfOrMerge(key, reader, choice)
          }
          return@forEachTag key
        }
      }
      reader.readUnknownField(tag)
    }
    if (mode == Mode.DEFER && hasMerges(reader)) {
      choice = finishOneOfMerge(reader, choice)
      endMerges(reader)
    }
    return Holder(choice)
  }
}

class DecodeOneOfMergeTest {
  private val adapters = Mode.values().map { HolderAdapter(it) }

  private fun node(vararg values: Int): ByteString {
    var bytes = ByteString.EMPTY
    for (v in values) bytes += int32(2, v)
    return lengthDelimited(1, bytes)
  }

  private fun text(value: String): ByteString = encode(TEXT.tag, ProtoAdapter.STRING, value)

  private fun <T> encode(tag: Int, adapter: ProtoAdapter<T>, value: T): ByteString {
    val buffer = Buffer()
    adapter.encodeWithTag(ProtoWriter(buffer), tag, value)
    return buffer.readByteString()
  }

  /** A `google.protobuf.Value` that sets the null value. */
  private val nullValue = lengthDelimited(VALUE.tag, int32(1, 0))

  private fun number(value: Double) = encode(VALUE.tag, ProtoAdapter.STRUCT_VALUE, value)

  private fun assertDecodes(expected: String, bytes: ByteString) {
    for (adapter in adapters) {
      assertThat(adapter.decode(bytes.toByteArray()).toString()).isEqualTo(expected)
      assertThat(adapter.decode(Buffer().write(bytes)).toString()).isEqualTo(expected)
    }
  }

  @Test fun repeatedMessageMemberIsMerged() {
    assertDecodes(
      "Holder(choice=key1=Node(child=null, values=[1, 2]))",
      node(1) + node(2),
    )
  }

  @Test fun anotherMemberReplacesTheCurrentOne() {
    assertDecodes("Holder(choice=key2=t)", node(1) + node(2) + text("t"))
    assertDecodes(
      "Holder(choice=key1=Node(child=null, values=[3, 4]))",
      node(1) + node(2) + text("t") + node(3) + node(4),
    )
  }

  @Test fun repeatedScalarMemberKeepsTheLastValue() {
    assertDecodes("Holder(choice=key2=b)", text("a") + text("b"))
  }

  @Test fun repeatedWrapperMemberKeepsTheLastValue() {
    val first = encode(WRAPPED.tag, ProtoAdapter.STRING_VALUE, "a")
    val second = encode(WRAPPED.tag, ProtoAdapter.STRING_VALUE, "b")
    assertDecodes("Holder(choice=key4=b)", first + second)
  }

  @Test fun nullValueAfterNumberGivesNull() {
    for (adapter in adapters) {
      for (decoded in listOf(
        adapter.decode((number(1.0) + nullValue).toByteArray()),
        adapter.decode(Buffer().write(number(1.0) + nullValue)),
      )) {
        assertThat(decoded.choice!!.key).isEqualTo(VALUE)
        assertThat(decoded.choice!!.value).isNull()
      }
    }
  }

  @Test fun numberAfterNullValueGivesNumber() {
    for (adapter in adapters) {
      val decoded = adapter.decode((nullValue + number(2.0)).toByteArray())
      assertThat(decoded.choice!!.value).isEqualTo(2.0)
    }
  }

  @Test fun noOccurrenceGivesNoMember() {
    for (adapter in adapters) {
      assertThat(adapter.decode(ByteArray(0)).choice).isNull()
    }
  }
}
