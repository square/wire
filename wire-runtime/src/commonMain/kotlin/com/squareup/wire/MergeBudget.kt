package com.squareup.wire

import com.squareup.wire.ProtoReader.Companion.DEFAULT_RECURSION_LIMIT
import com.squareup.wire.internal.ProtocolException
import okio.Buffer
import okio.ByteString

/**
 * State that all readers of one outermost decode share to merge repeated embedded messages.
 *
 * It counts the bytes that merging re-encodes during the decode. Code generated by older versions
 * of Wire merges the second occurrence of a singular message field by encoding the first
 * occurrence, appending the new bytes, and decoding the result. The work grows with the size of
 * everything merged so far. The count bounds that work to a fixed allowance plus a multiple of the
 * bytes the outermost reader consumed.
 *
 * It also holds the later occurrences of singular message fields that current generated code defers
 * until the end of the enclosing message, so that each field is merged once. See
 * [com.squareup.wire.internal.decodeMessageOrDefer].
 */
internal class MergeBudget {
  private var spent = 0L

  /** The messages being decoded that have deferred occurrences, outermost first. */
  private val frames = ArrayList<MergeFrame>()

  fun charge(byteCount: Long, allowance: Long) {
    spent += byteCount
    if (spent > allowance) {
      throw ProtocolException("Too much work merging repeated message fields")
    }
  }

  /** Returns true if a message that has ended at [depth] deferred any occurrence. */
  fun hasFrameAbove(depth: Int): Boolean = frames.isNotEmpty() && frames[frames.lastIndex].depth > depth

  /** Keeps [bytes], a later occurrence of [tag] in the message whose fields are at [context]. */
  fun defer(context: MergeContext, tag: Int, bytes: ByteString) {
    dropFramesDeeperThan(context.recursionDepth)
    var frame = frames.lastOrNull()
    if (frame == null || frame.depth != context.recursionDepth) {
      frame = MergeFrame(context.recursionDepth, context)
      frames += frame
    }
    frame.occurrences.getOrPut(tag) { Buffer() }.write(bytes)
  }

  /** Forgets the occurrences of [tag] kept for the message at [depth]. */
  fun discard(depth: Int, tag: Int) {
    dropFramesDeeperThan(depth)
    val frame = frames.lastOrNull() ?: return
    if (frame.depth == depth) frame.occurrences.remove(tag)
  }

  /**
   * Merges the occurrences kept for [tag] by the message that just ended at [depth] into
   * [existing], which is the first occurrence. Returns [existing] if none were kept.
   */
  fun <E> finish(depth: Int, tag: Int, adapter: ProtoAdapter<E>, existing: E?): E? {
    val frame = frames.lastOrNull()
    if (frame == null || frame.depth <= depth) return existing
    val pending = frame.occurrences.remove(tag) ?: return existing
    if (existing == null) return null
    val context = frame.context
    val buffer = Buffer()
    adapter.encode(buffer, existing)
    charge(buffer.size + pending.size, context.allowance)
    buffer.writeAll(pending)
    return adapter.decode(ProtoReader(buffer, context))
  }

  /** Forgets everything kept for the message that just ended at [depth]. */
  fun end(depth: Int) {
    dropFramesDeeperThan(depth)
  }

  /** Drops the frames of messages deeper than [depth], which have ended. */
  private fun dropFramesDeeperThan(depth: Int) {
    while (frames.isNotEmpty() && frames[frames.lastIndex].depth > depth) {
      frames.removeAt(frames.lastIndex)
    }
  }
}

private class MergeFrame(val depth: Int, val context: MergeContext) {
  val occurrences = LinkedHashMap<Int, Buffer>()
}

/**
 * What a nested decode needs from the reader that triggers a merge. The nested decode continues
 * the caller's recursion depth and shares its [budget].
 */
internal class MergeContext(
  val recursionLimit: Int,
  val recursionDepth: Int,
  val budget: MergeBudget,
  val allowance: Long,
)

/** Bytes of merge work allowed regardless of input size. */
internal const val MERGE_ALLOWANCE_BYTES = 512L * 1024 * 1024

/** Bytes of merge work allowed for each byte the outermost reader consumed. */
internal const val MERGE_ALLOWANCE_PER_INPUT_BYTE = 64L

internal fun allowedMergeBytes(bytesConsumed: Long): Long = MERGE_ALLOWANCE_BYTES + MERGE_ALLOWANCE_PER_INPUT_BYTE * bytesConsumed

/** Returns the merge context of [this], or one without limits if it is not a built-in reader. */
internal fun ProtoReader32.mergeContext(): MergeContext = (this as? ByteArrayProtoReader32)?.mergeContext()
  ?: MergeContext(DEFAULT_RECURSION_LIMIT, 0, MergeBudget(), Long.MAX_VALUE)
