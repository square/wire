package com.squareup.wire.gradle

import java.math.BigInteger
import java.util.concurrent.ConcurrentHashMap
import org.gradle.api.artifacts.ConfigurationContainer
import org.gradle.api.artifacts.component.ModuleComponentSelector
import org.gradle.api.artifacts.result.ComponentSelectionCause
import org.gradle.api.artifacts.result.ResolvedDependencyResult
import org.gradle.api.logging.Logger

/**
 * Warns when the version of a Wire artifact is not the one the user asked for, or is older than the
 * Wire Gradle plugin. The constraints of the plugin raise versions silently, and a pin such as
 * `resolutionStrategy.force` can win over them silently too.
 *
 * This listens to resolutions which happen anyway, and never resolves a configuration itself. It
 * holds a [Logger] and a configuration name, not a `Project`, so that it is configuration cache
 * safe. It only runs when Gradle runs the configuration phase, so a build which reuses the
 * configuration cache does not print the warnings again.
 */
internal class WireVersionAlignmentWarnings(
  private val logger: Logger,
  private val wireVersion: String,
  /** The configuration which holds the constraints. We only look at configurations extending it. */
  private val constraintsConfigurationName: String,
  private val alignedModules: List<String>,
) {
  private val warned = ConcurrentHashMap.newKeySet<String>()

  fun register(configurations: ConfigurationContainer) {
    configurations.configureEach { configuration ->
      configuration.incoming.afterResolve { resolvableDependencies ->
        if (configuration.hierarchy.none { it.name == constraintsConfigurationName }) return@afterResolve
        val root = resolvableDependencies.resolutionResult.root
        val configurationName = configuration.name

        // Case 1: the project declares an older version, and a constraint raised it.
        for (edge in root.dependencies) {
          if (edge !is ResolvedDependencyResult || edge.isConstraint) continue
          val requested = edge.requested as? ModuleComponentSelector ?: continue
          if (requested.group != GROUP || requested.module !in alignedModules) continue
          val declared = requested.version
          val resolved = edge.selected.moduleVersion?.version ?: continue
          if (declared.isEmpty()) continue
          if (compareVersions(declared, wireVersion) >= 0) continue
          if (compareVersions(resolved, wireVersion) < 0) continue
          val raisedByConstraint = edge.selected.selectionReason.descriptions.any {
            it.cause == ComponentSelectionCause.CONSTRAINT && it.description.contains(CONSTRAINT_REASON)
          }
          if (!raisedByConstraint) continue
          warnOnce("raised:${requested.module}") {
            "Wire artifact $GROUP:${requested.module}:$declared is declared in configuration " +
              "'$configurationName' but resolved to $resolved. " +
              "The Wire Gradle plugin aligns Wire artifacts to its version, $wireVersion, " +
              "because code it generates needs the matching Wire artifacts. " +
              "To silence this warning, declare ${requested.module} at $wireVersion or newer."
          }
        }

        // Case 2: a Wire artifact is older than the plugin, whatever the reason.
        for (component in resolvableDependencies.resolutionResult.allComponents) {
          val id = component.moduleVersion ?: continue
          if (id.group != GROUP || id.name !in alignedModules) continue
          if (compareVersions(id.version, wireVersion) >= 0) continue
          val reasons = component.selectionReason.descriptions
            .filter { it.cause !in uninformativeCauses }
            .map { it.description }
          warnOnce("kept:${id.name}") {
            "Wire artifact $GROUP:${id.name} resolves to ${id.version} in configuration " +
              "'$configurationName', which is older than the Wire Gradle plugin version, $wireVersion. " +
              (if (reasons.isEmpty()) "" else "Gradle selected it because: ${reasons.joinToString("; ")}. ") +
              "Code generated by the Wire Gradle plugin needs Wire artifacts at $wireVersion or newer. " +
              "Remove what pins ${id.name} to an older version, such as a forced version, " +
              "a substitution rule or an enforced platform."
          }
        }
      }
    }
  }

  private fun warnOnce(key: String, message: () -> String) {
    if (warned.add(key)) logger.warn(message())
  }

  internal companion object {
    private const val GROUP = "com.squareup.wire"

    /** Every selection has these, and the constraints of the plugin are not the reason of a pin. */
    private val uninformativeCauses = setOf(
      ComponentSelectionCause.REQUESTED,
      ComponentSelectionCause.ROOT,
      ComponentSelectionCause.CONSTRAINT,
    )

    /** The reason of the constraints, see [WirePlugin]. Gradle shows it in the selection reasons. */
    const val CONSTRAINT_REASON = "Align Wire artifacts to the version of the Wire Gradle plugin"

    /**
     * Compares two versions like Gradle: numbers by value, `1.0` equals `1.0.0`, and qualifiers
     * such as `alpha01` or `SNAPSHOT` are older than the same version without a qualifier.
     */
    fun compareVersions(a: String, b: String): Int {
      val left = tokens(a)
      val right = tokens(b)
      for (i in 0 until maxOf(left.size, right.size)) {
        val l = left.getOrNull(i) ?: ""
        val r = right.getOrNull(i) ?: ""
        val result = compareToken(l, r)
        if (result != 0) return result
      }
      return 0
    }

    private fun tokens(version: String): List<String> = Regex("[0-9]+|[A-Za-z]+").findAll(version).map { it.value }.toList()

    /** A missing token compares like `0` against a number, and like a release against a word. */
    private fun compareToken(l: String, r: String): Int {
      val lNumber = l.toBigIntegerOrNull()
      val rNumber = r.toBigIntegerOrNull()
      return when {
        lNumber != null && rNumber != null -> lNumber.compareTo(rNumber)
        l.isEmpty() && rNumber != null -> BigInteger.ZERO.compareTo(rNumber)
        r.isEmpty() && lNumber != null -> lNumber.compareTo(BigInteger.ZERO)
        lNumber != null -> 1
        rNumber != null -> -1
        else -> {
          val byRank = qualifierRank(l).compareTo(qualifierRank(r))
          if (byRank != 0) byRank else l.lowercase().compareTo(r.lowercase())
        }
      }
    }

    private fun qualifierRank(word: String): Int = when (word.lowercase()) {
      "dev" -> 0
      "rc", "cr" -> 2
      "snapshot" -> 3
      "", "final", "ga", "release" -> 4
      "sp" -> 5
      else -> 1
    }
  }
}
